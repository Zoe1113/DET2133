/**************************************************************************
函数名称：	LowTemp_Compensate()
函数功能：	温度靠拢算法
输入参数：	g_TpStep
输出参数：	g_TpStep
返回值  ：	无
占用空间：	TBD
备    注：
1、本程序只允许加不允许减；
2、注意Close_Temp和表格对应关系；
3、奇数和偶数与表格有关，不可以随意修改；
**************************************************************************/
void LowTemp_Compensate(void)
{
    bit F_OddFlag = 0;
	uint16 b;
	uint8 a;

	//高于37.0℃不做处理
	if( g_TpStep < 0x0E74 && g_TpStep > 0x0000)
	{
		b = g_TpStep/10;

		//如果目标温度＜27.2℃，则从27.2度起查表
		if( b < Close_Temp )
		{
			a = 0;
		}
		else
		{
			a = (uint8)(b - Close_Temp);
		}

		//如果最低位为奇数，则奇数标志位置1（和表格有关）
   		if( a & 0x01 == 0x01)
       		F_OddFlag =1;

		a = a>>1;

        //奇数取低字节，偶数取高字节
        if( F_OddFlag == 1)
		{
        	a = CloseTable[ a ] ;
		}
		else
        {
            a = CloseTable[ a ] >> 8;
        }

		g_TpStep += a;
	}
}


