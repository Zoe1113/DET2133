/**************************************************************************
函数名称：	Forehead_Compensate()
函数功能：	额温临床修正
输入参数：	g_TpStep、R_NtcStep
输出参数：	g_TpStep(修正后)
返回值  ：	无
占用空间：	TBD
备    注：	无
;请注意:
;①、本程序可根据实际修正表格做上下限调整
;②、本程序只针对人体，故均为无符号数
;③、本程序之前已经判断过NTC范围
;④、此程序修改必须进行测试（测试用例：目标温度低于26，目标温度高于41，环温正好为40）
**************************************************************************/
void Forehead_Compensate(void)
{
	uint16 value1,value2,value3;
	uint8 R_NtcSection,R_FTSection;
	bit F_NegFlag = 0;

	//先确定R_NtcSection区块
	//R_NtcSection=(g_NtcStep/100-10)/5
	//R_NtcSection = g_NtcStep / 500 - 2;
	R_NtcSection = g_NtcStep / 500 ;   //20220214修改人体修正由10~40℃改为0~40℃

	//再确定R_FTSection区块
	//R_FTSection=((g_TpStep)/10-260)/5=(g_TpStep)/50-52
	if ( g_TpStep < 2600 )
	{
		R_FTSection = 0;
		g_TpStep += S_NtcFTValue(R_NtcSection,R_FTSection);
	}
	else if ( g_TpStep > 4100 )
	{
		R_FTSection = 30;
		g_TpStep += S_NtcFTValue(R_NtcSection,R_FTSection);
	}
	else
	{
		R_FTSection = g_TpStep / 50 - 52;			//目标起始温度26，步长0.5, 26除以0.5

		//插值法计算当前R_NtcStep对应的R_FTSection修正值
		value1 = S_NtcFTValue(R_NtcSection,R_FTSection);

		//插值法计算当前R_NtcStep对应的R_FTSection+1修正值
		R_FTSection += 1;
		value2 = S_NtcFTValue(R_NtcSection,R_FTSection);

		//计算最终的修正值，此处可能会存在正负问题
		if ( value1 < value2 )
		{
			value1 = value2 - value1;
			F_NegFlag = 1;
		}
		else
		{
			value1 -= value2;
		}

		value3 = (uint16)R_FTSection * 50 + 2600;

		value1 = value1 * ( value3 - g_TpStep) / 50;

		value3 = value2 + value1;
		if(F_NegFlag)
		{
			value3 = value2 - value1;
		}
		g_TpStep += value3;
	}
}

/**************************************************************************
函数名称：	Forehead_Compensate()
函数功能：	额温临床修正
输入参数：	g_TpStep、R_NtcStep
输出参数：	g_TpStep(修正后)
返回值  ：	无
占用空间：	TBD
备    注：	无
;请注意:
;①、本程序可根据实际修正表格做上下限调整
;②、本程序只针对人体，故均为无符号数
;③、本程序之前已经判断过NTC范围
**************************************************************************/

uint16 S_NtcFTValue(uint8 R_NtcSection, uint8 R_FTSection)
{
	uint8 F_OddFlag = 0;
	uint8 a,b;
	uint16 i,c,value;

	//如果最低位为奇数，则奇数标志位置1（和表格有关）
	if (R_FTSection & 0x01 == 0x01)
	{
		F_OddFlag = 1;
	}

	R_FTSection = R_FTSection >> 1;

	//插值法计算当前R_NtcStep对应的R_FTSection修正值
	i = (uint16)R_NtcSection * 16 + R_FTSection;

	if(F_OddFlag == 1)
	{
		a = FTOffsetTable[i] >> 8;
	}
	else
	{
		a = FTOffsetTable[i];
	}

	//如果R_NtcSection正好是40度，则b为0
	if ( R_NtcSection != 8 )	//如果不在第八个环境分段
	{
		i = (uint16)(R_NtcSection + 1) * 16 + R_FTSection;

		if(F_OddFlag == 1)
		{
			b = FTOffsetTable[i] >> 8;
		}
		else
		{
			b = FTOffsetTable[i] ;
		}
		//此处a一定大于b;
		a = a - b;
		//计算Value
		c = (uint16)(R_NtcSection + 1) * 500;	//加1是为啥	，获取更高位表格数据？		//加1是在环温不在5的倍数时，求环温相临两行的平均值
		value = ( c - g_NtcStep ) * a / 500 ;			
		value +=  b;
		value *= 10;
	}
	else
	{
		value = a;
		value *= 10;
	}
	return value;
}

